#!/usr/bin/env python3
"""Generate LOGS/w1_fair_comparison/paper_tables.tex + results_tables.md from stats.json."""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
OUT = REPO / "LOGS/w1_fair_comparison"
S = json.loads((OUT / "stats.json").read_text())
COST = json.loads((OUT / "cost.json").read_text()) if (OUT / "cost.json").exists() else {}
MON = S.get("monitor", {})

ARMS = [("GRAD", "GRAD (graph)"), ("TXT", "Text-only (char CNN)"),
        ("TEMP", "Temporal (char CNN + Transformer)")]


def fm(x: float, d: int = 3) -> str:
    return f"{x:.{d}f}"


def delta_pair(a: str, b: str):
    p = S["paired"].get(f"{a}-{b}")
    flip = False
    if not p:
        p = S["paired"].get(f"{b}-{a}")
        flip = True
    if not p or "seed_mean" not in p:
        return None
    sm = p["seed_mean"]
    d, lo, hi = sm["delta"], sm["ci_lo"], sm["ci_hi"]
    if flip:
        d, lo, hi = -d, -hi, -lo
    return {"delta": d, "ci_lo": lo, "ci_hi": hi,
            "per_seed": [(e["seed"], (-e["delta"] if flip else e["delta"]),
                          (-e["ci_hi"] if flip else e["ci_lo"]),
                          (-e["ci_lo"] if flip else e["ci_hi"]),
                          e["excludes_zero"]) for e in p["per_seed"]],
            "seeds_excl": sum(1 for e in p["per_seed"] if e["excludes_zero"]),
            "n_seeds": len(p["per_seed"])}


def delta_row(a: str, b: str) -> str:
    d = delta_pair(a, b)
    if d is None:
        return "--"
    return (f"$\\Delta$AUROC {d['delta']:+.3f} "
            f"[{d['ci_lo']:+.3f}, {d['ci_hi']:+.3f}] (seed-mean, cluster bootstrap); "
            f"{d['seeds_excl']}/{d['n_seeds']} per-seed CIs exclude 0")


lines = []
lines.append("% W1 fair comparison tables (auto-generated by make_tables.py)")
lines.append("% Decision-time obs1: attacks truncated before harmful-action execution,")
lines.append("% proposed action visible; text 200 chars/step identical across arms.")
lines.append("% Test split exposed in earlier rounds: revised comparison, not confirmation.")
lines.append(r"\begin{table}[t]")
lines.append(r"\centering\small")
lines.append(r"\caption{Decomposition detection under the unified decision-time protocol "
             r"(obs1, 232 test cases; 3 seeds 211--213). Attacks are truncated at the "
             r"proposed harmful step; all continuous-score arms are retrained on the same "
             r"truncated corpus with the same budget and dev rule. $\Delta$AUROC uses a "
             r"95\% base-case cluster bootstrap (58 test groups). The sequential monitor "
             r"is a binary method at its native threshold and is listed separately.}")
lines.append(r"\label{tab:w1_decomp}")
lines.append(r"\begin{tabular}{lccc}")
lines.append(r"\hline")
lines.append(r"Method & AUROC $\uparrow$ & $\Delta$AUROC vs GRAD & TPR / FPR at dev thr. \\")
lines.append(r"\hline")
for arm, label in ARMS:
    a = S["arms"].get(arm)
    if not a:
        continue
    au = f"{a['auroc_mean']:.3f} $\\pm$ {a['auroc_std']:.3f}"
    dl = "--" if arm == "GRAD" else delta_row(arm, "GRAD")
    if "tpr_at_dev_threshold" in a:
        tpr = sum(a["tpr_at_dev_threshold"]) / len(a["tpr_at_dev_threshold"])
        fpr = sum(a["fpr_at_dev_threshold"]) / len(a["fpr_at_dev_threshold"])
        tf = f"{tpr:.2f} / {fpr:.2f}"
    else:
        tf = "--"
    lines.append(f"{label} & {au} & {dl} & {tf} \\\\")
lines.append(r"\hline")
if MON:
    nb = MON["native_binary"]
    lines.append(f"Sequential monitor (binary, native) & "
                 f"{MON['derived_ordinal_auroc']:.3f}$^\\dagger$ & -- & "
                 f"{nb['tpr']:.2f} / {nb['fpr']:.2f} \\\\")
lines.append(f"Length-only control & {S['length_only_auroc']:.3f} & -- & -- \\\\")
lines.append(r"\hline")
lines.append(r"\end{tabular}")
lines.append(r"\vspace{2pt}")
lines.append(r"\footnotesize{$^\dagger$Ordinal AUROC derived from the cached binary "
             r"prefix judgments (earlier first trigger $=$ higher risk); not a native "
             r"continuous risk. Monitor outputs were reused offline (deepseek-chat, "
             r"cumulative BINARY\_BASELINE, 2026-09-16 cache, zero new API calls). "
             f"Length-only controls for trace-length shortcuts (attack prefix vs benign "
             f"full trace).")
lines.append(r"\end{table}")
lines.append("")

lines.append(r"\begin{table}[t]")
lines.append(r"\centering\small")
lines.append(r"\caption{Appendix: out-of-protocol (full-trace) and same-observation "
             r"results retained for reference. Decomposition full-trace numbers are the "
             r"frozen GRAD-repair confirmation (legacy exposed test, 3 seeds); MCP/MRT "
             r"use the same split and same observation for all three arms; MINJA uses "
             r"group-disjoint CV (3 folds $\times$ 3 seeds, OOF).}")
lines.append(r"\label{tab:w1_appendix}")
lines.append(r"\begin{tabular}{lccc}")
lines.append(r"\hline")
lines.append(r"Method & Decomp (full trace) & MCP & MRT \\")
lines.append(r"\hline")
lines.append(r"GRAD-512 & 0.972 & 0.776 & 0.866 \\")
lines.append(r"Text-only 512 & 0.868 & 0.799 & 0.829 \\")
lines.append(r"Structure-only 512 & 0.864 & 0.674 & 0.861 \\")
lines.append(r"\hline")
lines.append(r"GRAD $-$ Text-only & $+0.104$ & $-0.023$ & $+0.037$ \\")
lines.append(r"\hline")
lines.append(r"\end{tabular}")
lines.append(r"\vspace{2pt}")
lines.append(r"\footnotesize{Decomp full-trace: paired group-clustered per-seed 95\% CIs "
             r"$[+0.042,+0.146]$, $[+0.054,+0.176]$, $[+0.055,+0.164]$ (mean $+0.104$); "
             r"MCP $[-0.087,+0.028]$, $[-0.082,+0.032]$, $[-0.080,+0.052]$ (mean $-0.023$); "
             r"MRT per-seed point deltas $+0.130$, $-0.030$, $+0.012$ (mean $+0.037$, "
             r"task-level sign tests n.s.). MINJA (same observation, "
             r"group-disjoint CV): GRAD $0.824\pm0.012$, Text-only $0.760\pm0.053$, "
             r"Structure-only $0.649\pm0.013$; GRAD$-$Text-only $+0.064\pm0.046$ with "
             r"only 1/3 family CIs excluding 0 (no established advantage); bag-of-words "
             r"XGB on the same corpus reaches $0.986$, so the MINJA corpus supports only "
             r"limited conclusions. Old numbers are retained, not merged with Table "
             r"\ref{tab:w1_decomp}.}")
lines.append(r"\end{table}")

tex = "\n".join(lines) + "\n"
(OUT / "paper_tables.tex").write_text(tex)

md = ["# W1 fair comparison — generated tables", "",
      "## Table 1 (main): Decomp obs1 (232 test, seeds 211-213)", "",
      "| Method | AUROC | ΔAUROC vs GRAD | TPR / FPR @ dev thr |", "|---|---|---|---|"]
for arm, label in ARMS:
    a = S["arms"].get(arm)
    if not a:
        md.append(f"| {label} | -- | -- | -- |")
        continue
    au = f"{a['auroc_mean']:.3f} ± {a['auroc_std']:.3f}"
    dl = "--" if arm == "GRAD" else delta_row(arm, "GRAD")
    if "tpr_at_dev_threshold" in a:
        tpr = sum(a["tpr_at_dev_threshold"]) / len(a["tpr_at_dev_threshold"])
        fpr = sum(a["fpr_at_dev_threshold"]) / len(a["fpr_at_dev_threshold"])
        tf = f"{tpr:.2f} / {fpr:.2f}"
    else:
        tf = "--"
    md.append(f"| {label} | {au} | {dl} | {tf} |")
if MON:
    nb = MON["native_binary"]
    md.append(f"| Sequential monitor (binary) | {MON['derived_ordinal_auroc']:.3f} (derived) "
              f"| -- | {nb['tpr']:.2f} / {nb['fpr']:.2f} |")
md.append(f"| Length-only control | {S['length_only_auroc']:.3f} | -- | -- |")
md.append("")
md.append("## Cost")
md.append("")
md.append("| arm | params | checkpoint | p50 latency (batch=1, CPU) | p95 |")
md.append("|---|---|---|---|---|")
for arm, label in ARMS:
    c = COST.get(arm)
    a = S["arms"].get(arm)
    if not c:
        continue
    md.append(f"| {label} | {c['params']:,} | {c['checkpoint_bytes']/1e6:.2f} MB | "
              f"{c['median_ms']:.1f} ms | {c['p95_ms']:.1f} ms |")
if MON:
    md.append(f"| Sequential monitor | deepseek-chat (API) | cached | -- | -- |")
md.append("")
(OUT / "results_tables.md").write_text("\n".join(md) + "\n")


def pct(x: float) -> str:
    return f"{100*x:.2f}"


man_path = OUT / "data/obs1/manifest.json"
man = json.loads(man_path.read_text()) if man_path.exists() else {}
R = ["# W1 fair comparison — results", "",
     "## 1. Protocol (obs1, frozen)", "",
     "- Decision time: immediately before the harmful step executes; the",
     "  proposed harmful action is visible; no later step is visible.",
     "- Source split: `code/repro/out/unified_gnn/fix2_splits/decomp/fold0`",
     "  (group-disjoint; unchanged). Test = 232 cases (174 attack / 58 benign),",
     "  58 base-case groups.",
     "- Text: every arm gets the same 200-char step strings (converter cap).",
     "- Learned arms (GRAD / Text-only / Temporal) retrained from scratch on the",
     "  truncated corpus; uniform budget 60 epochs / patience 15 / batch 48 /",
     "  lr 1e-3; dev selection = fixed-FPR F1 at target FPR 0.10; seeds 211-213.",
     "- Test split exposed earlier: revised comparison, not confirmation.",
     ""]
if man:
    for role in ("train", "dev", "test"):
        s = man["splits"][role]
        R.append(f"- {role}: n={s['n']}, pos={s['n_pos']}, attacks truncated="
                 f"{s['n_attacks_truncated']}, mean nodes {s['mean_nodes_before']} -> "
                 f"{s['mean_nodes_after']}, sha256={s['sha256'][:16]}…")
    R.append("")
R += ["## 2. Main results (Decomp obs1)", "", "| Method | AUROC | ΔAUROC vs GRAD | TPR / FPR @ dev thr |",
      "|---|---|---|---|"]
for arm, label in ARMS:
    a = S["arms"].get(arm)
    if not a:
        R.append(f"| {label} | pending | -- | -- |")
        continue
    au = f"{a['auroc_mean']:.3f} ± {a['auroc_std']:.3f} (seeds {a['seeds']})"
    dl = "--" if arm == "GRAD" else delta_row(arm, "GRAD")
    R.append(f"| {label} | {au} | {dl} | "
             f"{sum(a['tpr_at_dev_threshold'])/len(a['tpr_at_dev_threshold']):.2f} / "
             f"{sum(a['fpr_at_dev_threshold'])/len(a['fpr_at_dev_threshold']):.2f} |")
if MON:
    nb = MON["native_binary"]
    R.append(f"| Sequential monitor (binary, native thr) | "
             f"{MON['derived_ordinal_auroc']:.3f} (derived ordinal) | -- | "
             f"{nb['tpr']:.2f} / {nb['fpr']:.2f} |")
R.append(f"| Length-only control | {S['length_only_auroc']:.3f} | -- | -- |")
R.append("")
R.append("Per-seed AUROC and paired bootstrap details are in `stats.json`;")
R.append("per-example scores in `predictions/per_example_predictions.csv`.")
R.append("")
if MON:
    R += ["## 3. Sequential monitor (offline reuse)", "",
          f"- Cache: `{MON['cache']}` — {MON['model']}, prompt {MON['prompt']}, "
          f"mode {MON['eval_mode']}, {MON['n_tasks']} tasks, {MON['cache_batch_calls']} calls, "
          f"CNY {MON['cache_batch_rmb']} total; **zero new API calls**.",
          f"- Decision rule: attack detected iff a trigger occurs in the prefix through "
          f"the harmful step ({MON['attacks_truncated_prefix']} attack prefixes truncated); "
          f"benign detected iff flagged anywhere.",
          f"- Binary: TP={nb['tp']} FP={nb['fp']} TN={nb['tn']} FN={nb['fn']} "
          f"(TPR {nb['tpr']:.3f}, FPR {nb['fpr']:.3f}).",
          f"- Derived ordinal AUROC {MON['derived_ordinal_auroc']:.3f} "
          f"(flagged as derived, not native).",
          "- Small discrepancy with the cache's own summary (FP=21 vs our FP=22) is due to "
          "different task-level aggregation; our uniform prefix rule is applied to all arms.",
          ""]
R += ["## 4. Cost", ""]
if COST:
    R += ["| arm | params | checkpoint | p50 / p95 latency (batch=1, CPU) |", "|---|---|---|---|"]
    for arm, label in ARMS:
        c = COST.get(arm)
        if c:
            R.append(f"| {label} | {c['params']:,} | {c['checkpoint_bytes']/1e6:.2f} MB | "
                     f"{c['median_ms']:.1f} / {c['p95_ms']:.1f} ms |")
if MON:
    R.append(f"| Sequential monitor | hosted API | n/a | {MON['cache_batch_calls']} calls "
             f"for {MON['n_tasks']} cases (cache) |")
R.append("")
R += ["## 5. Out-of-protocol appendix (retained, not merged)", "",
      "- Decomp full trace (frozen GRAD-repair confirmation, legacy exposed test): "
      "GRAD-512 0.972, Text-only-512 0.868, Structure-only 0.864; paired "
      "GRAD$-$Text mean +0.104 with per-seed CIs all above 0.",
      "- MCP same split/observation: GRAD 0.776, Text-only 0.799, Structure-only 0.674; "
      "paired GRAD$-$Text mean -0.023 with all per-seed CIs including 0 (no advantage).",
      "- MRT same split/observation: GRAD 0.866, Text-only 0.829, Structure-only 0.861; "
      "paired GRAD$-$Text mean +0.037 with task-level sign tests n.s.",
      "- MINJA (same observation, group-disjoint CV): GRAD 0.824±0.012, Text 0.760±0.053, "
      "Structure 0.649±0.013; GRAD$-$Text +0.064±0.046 (1/3 CIs >0); BoW XGB 0.986.",
      "- No complete-defense reproduction is claimed; the monitor is a cached binary "
      "comparator and GRAD is a detector, not a deployed guardrail.",
      ""]
(OUT / "results.md").write_text("\n".join(R) + "\n")
print(tex)
print("wrote paper_tables.tex, results_tables.md, results.md")
