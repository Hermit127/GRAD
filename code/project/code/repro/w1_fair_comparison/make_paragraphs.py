#!/usr/bin/env python3
"""Emit directly replaceable manuscript paragraphs from W1 stats.json."""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
OUT = REPO / "LOGS/w1_fair_comparison"
S = json.loads((OUT / "stats.json").read_text())
MON = S.get("monitor", {})
A = S["arms"]


def au(arm: str) -> str:
    a = A.get(arm)
    if not a:
        return "n/a"
    return f"{a['auroc_mean']:.3f} $\\pm$ {a['auroc_std']:.3f}"


def delta_txt(a: str, b: str) -> str:
    p = S.get("paired", {}).get(f"{a}-{b}")
    if not p or "seed_mean" not in p:
        return "n/a"
    sm = p["seed_mean"]
    return (f"{sm['delta']:+.3f} [{sm['ci_lo']:+.3f}, {sm['ci_hi']:+.3f}] "
            f"(seed-averaged, base-case cluster bootstrap)")


def tf(arm: str) -> str:
    a = A.get(arm)
    if not a or "tpr_at_dev_threshold" not in a:
        return "n/a"
    tpr = sum(a["tpr_at_dev_threshold"]) / len(a["tpr_at_dev_threshold"])
    fpr = sum(a["fpr_at_dev_threshold"]) / len(a["fpr_at_dev_threshold"])
    return f"{tpr:.2f}/{fpr:.2f}"


def pair(a: str, b: str):
    p = S.get("paired", {}).get(f"{a}-{b}")
    flip = False
    if not p:
        p = S.get("paired", {}).get(f"{b}-{a}")
        flip = True
    if not p or "seed_mean" not in p:
        return None
    sm = p["seed_mean"]
    d, lo, hi = sm["delta"], sm["ci_lo"], sm["ci_hi"]
    if flip:
        d, lo, hi = -d, -hi, -lo
    return {"delta": d, "lo": lo, "hi": hi,
            "seeds": [(-e["delta"], -e["ci_hi"], -e["ci_lo"]) if flip
                      else (e["delta"], e["ci_lo"], e["ci_hi"]) for e in p["per_seed"]],
            "n_excl": sum(1 for e in p["per_seed"] if e["excludes_zero"]),
            "n": len(p["per_seed"])}


gt = pair("GRAD", "TXT")
gm = pair("GRAD", "TEMP")
mt = pair("TEMP", "TXT")
claim_parts = []
if gt:
    claim_parts.append(
        f"GRAD exceeds the text-only encoder by {gt['delta']:+.3f} "
        f"[{gt['lo']:+.3f}, {gt['hi']:+.3f}] (seed-averaged; "
        f"{gt['n_excl']}/{gt['n']} per-seed CIs exclude zero)")
if gm:
    claim_parts.append(
        f"GRAD exceeds the order-aware temporal model by {gm['delta']:+.3f} "
        f"[{gm['lo']:+.3f}, {gm['hi']:+.3f}] ({gm['n_excl']}/{gm['n']} per-seed CIs exclude zero)")
if mt:
    claim_parts.append(
        f"the temporal model over the plain text encoder is "
        f"{'established' if mt['lo'] > 0 else 'not established'} "
        f"({mt['delta']:+.3f} [{mt['lo']:+.3f}, {mt['hi']:+.3f}], "
        f"{mt['n_excl']}/{mt['n']} per-seed CIs exclude zero)")
claim = "; ".join(claim_parts) + "." if claim_parts else "Results pending."
claim = claim[0].upper() + claim[1:]


txt = f"""# Directly replaceable manuscript text (W1 fair comparison)

> Generated by `code/repro/w1_fair_comparison/make_paragraphs.py` from
> `stats.json`; numbers refer to Table 1 (Decomp obs1, 232 test cases,
> seeds 211-213). The test split was exposed in earlier rounds: this is a
> clearly-labelled revised comparison, not independent confirmation.

## 1. Abstract (replace the sweeping advantage sentence)

"On decomposition traces we evaluate all components at the same decision
moment: every input is truncated immediately before the harmful step executes,
the proposed action is visible, and no later step is observable. Under this
matched protocol, GRAD attains AUROC {au('GRAD')}, text-only {au('TXT')}, and an
order-aware temporal text model {au('TEMP')}. The previously reported
double-digit percentage-point advantage was obtained under heterogeneous
visibility and truncation protocols and is withdrawn; the matched comparison
reports the differences with base-case clustered intervals."

## 2. Contributions (replace the broad superiority bullet)

"- We define a unified decision-time evaluation for runtime agent defense:
  attacks are truncated at the proposed harmful action, the same per-step text
  (200 characters, as stored by the converter) is given to every arm, and all
  learned arms are retrained from scratch on the same truncated corpus with one
  budget and one development-selection rule. Under this protocol we report
  AUROC {au('GRAD')} for GRAD, {au('TXT')} for a text-only encoder, and
  {au('TEMP')} for an order-aware Transformer over the same step encoder. The
  matched GRAD $-$ text-only difference is {delta_txt('GRAD', 'TXT')} and the
  GRAD $-$ temporal difference is {delta_txt('GRAD', 'TEMP')}; we report these
  effects with base-case clustered intervals instead of headline gaps between
  heterogeneous protocols."

## 3. Experiments: protocol paragraph (insert before the main table)

"\\paragraph{{Unified decision-time protocol.}} All methods are evaluated at the
same moment: immediately before the harmful step executes. For attack traces we
keep the prefix through the proposed harmful step and drop every later step; the
proposed action itself is visible. Benign traces are unchanged. Every arm
receives the same per-step subtask string (200 characters, the convention of the
converter). The three learned arms (GRAD, text-only encoder, and an order-aware
Transformer that reuses the same character encoder over turn-ordered steps) are
retrained from scratch on the truncated training split, with identical budget
(60 epochs, patience 15, batch 48, AdamW $10^{{-3}}$), identical seeds, and a
development-selected threshold at a target FPR of 0.10. The sequential monitor
is a binary comparator evaluated at its native threshold; its cached judgments
on the same cases are reused offline, and the proposed action is included in its
decision prefix. The test split was used in earlier rounds, so this is a revised
comparison under the matched protocol, not an independent confirmation."

## 4. Results paragraph (replace the old advantage claim)

"\\paragraph{{Matched decomposition comparison.}} Table~\\ref{{tab:w1_decomp}}
reports the matched comparison. GRAD reaches AUROC {au('GRAD')}, the text-only
encoder {au('TXT')}, and the temporal model {au('TEMP')}. The paired differences
are GRAD $-$ text-only {delta_txt('GRAD', 'TXT')}, GRAD $-$ temporal
{delta_txt('GRAD', 'TEMP')}, and temporal $-$ text-only
{delta_txt('TEMP', 'TXT')}. At the development-selected threshold the test
TPR/FPR are {tf('GRAD')}, {tf('TXT')}, and {tf('TEMP')}, respectively. The
sequential monitor is binary: it flags {MON.get('native_binary', {}).get('tpr', float('nan')):.2f}
of attacks at or before the proposed harmful step and
{MON.get('native_binary', {}).get('fpr', float('nan')):.2f} of benign traces at
its native threshold; its derived ordinal AUROC (earlier first trigger ranked
higher) is {MON.get('derived_ordinal_auroc', float('nan')):.3f}. A length-only
control reaches AUROC {S['length_only_auroc']:.3f}, so we also report the
length distribution. {claim} We do not claim a general advantage from graph
modeling, and the test split having been exposed earlier, these numbers are a
revised comparison rather than independent confirmation."

## 5. Limitations sentences (insert)

"- The decomposition test split has been exposed in prior rounds; the matched
  comparison is a revised evaluation and is not independent confirmation.
- The sequential monitor is a hosted model; its cost is per API call
  ({MON.get('cache_batch_calls', 'n/a')} cached calls, CNY
  {MON.get('cache_batch_rmb', 'n/a')} for the {MON.get('n_tasks', 'n/a')} test
  cases) and it is listed separately from the continuous-score detectors.
- We do not claim a reproduction of any complete defense system: the monitor
  arm reuses cached binary judgments, and the graph arm is a trained detector,
  not a deployed end-to-end guardrail."

## 6. Appendix framing (out-of-protocol results)

"The full-trace decomposition results from the frozen GRAD-repair confirmation
(GRAD 0.972 / text-only 0.868 / structure-only 0.864) and the MCP/MRT
same-split comparison (GRAD 0.776/0.866, text-only 0.799/0.829, structure-only
0.674/0.861) were produced before the visibility protocol was unified. They are
retained in Appendix Table~\\ref{{tab:w1_appendix}} for traceability only and
are not merged with Table~\\ref{{tab:w1_decomp}}."
"""
(OUT / "paper_paragraphs.md").write_text(txt)
print(txt)
