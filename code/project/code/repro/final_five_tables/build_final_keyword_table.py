#!/usr/bin/env python3
"""Build the final keyword ablation table (legacy vs sealed independent).

Rows: Final GRAD (no keywords), Final GRAD + lexical indicators, matched
structure-only / text-only / chronological-only.
Columns: Decomp / MCP / MRT legacy (previously viewed test) and sealed
group-isolated MCP (independent; same CPU hardware branch for all rows).

Writes LOGS/final_five_tables/table5/table5_final_keyword.{tex,json}
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[3]
LEGACY = REPO / "code/repro/out/table5_ablation/runs"
ARCH = REPO / "code/repro/out/unified_gnn/runs"
SEALED_K1 = REPO / "code/repro/out/table5_keyword/sealed_cpu"
SEALED_REF = REPO / "code/repro/out/table5_candidates/sealed_cpu"
OUT = REPO / "LOGS/final_five_tables/table5"
SEEDS = [211, 212, 213]
LEGACY_CELLS = {
    "decomp": ["fold0"],
    "mcp": [f"fold{k}" for k in range(5)],
    "mrt": [f"fold_{t}" for t in ("american_airlines_2", "api_key_calendar_agendas_2",
                                  "bank_transfer_2", "expenditure_accounting",
                                  "spam_filter_update")],
}
ROWS = {
    "Final GRAD (no keywords)": {"legacy": "no_keyword_features", "sealed": "k1"},
    "Final GRAD + lexical indicators": {"legacy": "full", "sealed": "full"},
    "matched structure-only": {"legacy": "structure_only", "sealed": "structure_only"},
    "matched text-only": {"legacy": "text_only", "sealed": "text_only"},
    "matched chronological-only": {"legacy": "chrono_only", "sealed": "chrono_only"},
}


def auroc(y, s):
    y = np.asarray(y); s = np.asarray(s, dtype=float)
    pos, neg = y == 1, y == 0
    if pos.sum() == 0 or neg.sum() == 0:
        return float("nan")
    order = np.argsort(s); ss = s[order]
    ranks = np.empty(len(s)); i = 0
    while i < len(s):
        j = i
        while j + 1 < len(s) and ss[j + 1] == ss[i]:
            j += 1
        ranks[order[i:j + 1]] = (i + j) / 2 + 1
        i = j + 1
    return float((ranks[pos].sum() - pos.sum() * (pos.sum() + 1) / 2)
                 / (pos.sum() * neg.sum()))


def legacy_series(variant, ds):
    vals = []
    for seed in SEEDS:
        cells = []
        for cell in LEGACY_CELLS[ds]:
            p = LEGACY / f"{ds}_{cell}_{variant}_s{seed}.json"
            if not p.exists() and ds == "mrt" and variant == "full":
                p = ARCH / f"mrt_{cell.replace('fold_', '')}_s{seed}.json"
            if not p.exists():
                continue
            d = json.loads(p.read_text())
            rows = d["scores"]["test"]
            a = auroc([r["label"] for r in rows], [r["score"] for r in rows])
            npos = sum(r["label"] for r in rows)
            cells.append((a, npos * (len(rows) - npos)))
        if cells:
            vals.append(np.average([a for a, _ in cells], weights=[w for _, w in cells]))
    return vals


def sealed_series(label):
    vals = []
    for seed in SEEDS:
        if label == "k1":
            p = SEALED_K1 / f"k1_s{seed}" / f"gnn_v2_results_sealed_k1_s{seed}.json"
            if not p.exists():
                cands = sorted((SEALED_K1 / f"k1_s{seed}").glob("gnn_v2_results_*.json"))
                p = cands[-1] if cands else p
        else:
            p = SEALED_REF / f"{label}_s{seed}.json"
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        rows = d.get("scores", {}).get("test", [])
        if len(rows) == 0 and "test" in d and isinstance(d["test"], dict):
            rows = []   # instrumentation-style not expected here
        if rows:
            vals.append(auroc([r["label"] for r in rows], [r["score"] for r in rows]))
    return vals


def main() -> int:
    out = {"legacy": {}, "sealed": {}}
    for name, spec in ROWS.items():
        out["legacy"][name] = {}
        for ds in LEGACY_CELLS:
            v = legacy_series(spec["legacy"], ds)
            out["legacy"][name][ds] = {
                "mean": float(np.mean(v)) if v else None,
                "std": float(np.std(v)) if v else None,
                "per_seed": [round(x, 4) for x in v], "n_seeds": len(v)}
        v = sealed_series(spec["sealed"])
        out["sealed"][name] = {
            "mean": float(np.mean(v)) if v else None,
            "std": float(np.std(v)) if v else None,
            "per_seed": [round(x, 4) for x in v], "n_seeds": len(v)}

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "table5_final_keyword.json").write_text(json.dumps(out, indent=1))

    def cell(d):
        if d["mean"] is None:
            return "--"
        return f"{d['mean']:.3f}$\\pm${d['std']:.3f}"

    lines = [
        "% Final keyword ablation. AUTO-GENERATED by build_final_keyword_table.py.",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\caption{Keyword-channel decision for the final GRAD. `Final GRAD' deletes "
        "the 9 handcrafted keyword indicators (dimension removal, retrained); "
        "`+ lexical indicators' is the original full input. Sealed MCP is the "
        "group-isolated split never used in development (CPU branch; all rows same "
        "hardware); legacy columns were previously viewed during earlier reporting "
        "and are replication, not independent confirmation.}",
        "\\label{tab:final_keyword}",
        "\\begin{tabular}{@{}lcccc@{}}",
        "\\toprule",
        " & \\multicolumn{3}{c}{Legacy replication (AUROC)} & Sealed MCP \\\\",
        "\\cmidrule(lr){2-4}\\cmidrule(lr){5-5}",
        "\\textit{Method} & Decomp & MCP & MRT & AUROC \\\\",
        "\\midrule",
    ]
    for name in ROWS:
        l = out["legacy"][name]
        s = out["sealed"][name]
        lines.append(f"{name} & {cell(l['decomp'])} & {cell(l['mcp'])} & "
                     f"{cell(l['mrt'])} & {cell(s)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (OUT / "table5_final_keyword.tex").write_text("\n".join(lines))
    print("wrote table5_final_keyword.{tex,json}")
    print(json.dumps(out, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
